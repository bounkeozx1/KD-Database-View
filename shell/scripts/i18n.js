function _detectDefaultLang() {
  // 1) Honour an explicit saved choice.
  try { const saved = localStorage.getItem('kd_lang'); if (saved && I18N[saved]) return saved; } catch (e) {}
  // 2) Otherwise follow the device language (English device → English, Lao device → Lao, …).
  try {
    const nav = (navigator.language || navigator.userLanguage || '').toLowerCase();
    if (nav.startsWith('lo')) return 'lo';
    if (nav.startsWith('th')) return 'th';
    if (nav.startsWith('ko')) return 'ko';
    if (nav.startsWith('en')) return 'en';
  } catch (e) {}
  // 3) Fall back to a timezone hint.
  try {
    const tz = Intl.DateTimeFormat().resolvedOptions().timeZone || '';
    if (tz === 'Asia/Seoul' || tz === 'Asia/Pyongyang') return 'ko';
    if (tz === 'Asia/Vientiane') return 'lo';
    if (tz === 'Asia/Bangkok') return 'th';
  } catch (e) {}
  return 'en';
}
let currentLang = _detectDefaultLang();

function t(key, vars) {
  const dict = I18N[currentLang] || I18N.en;
  let str = dict[key] || I18N.en[key] || key;
  if (vars) Object.entries(vars).forEach(([k, v]) => { str = str.replace('{' + k + '}', v); });
  return str;
}

function setLang(lang) {
  if (!I18N[lang]) return;
  currentLang = lang;
  localStorage.setItem('kd_lang', lang);
  applyTranslations();
}

function applyTranslations() {
  // Elements with data-i18n attribute get their textContent replaced
  document.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(el.dataset.i18n);
  });
  // Elements with data-i18n-placeholder get their placeholder replaced
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    el.placeholder = t(el.dataset.i18nPh);
  });
  // Elements with data-i18n-title get their title (tooltip) replaced
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    el.title = t(el.dataset.i18nTitle);
  });
  // Inline multilingual labels — pick the attribute matching the current
  // language, falling back to English then Lao. Now covers all 4 languages
  // (data-en/th/lo/ko and data-ph-en/th/lo/ko), not just Lao-or-English.
  const _pickLangAttr = (el, prefix) => {
    const order = [currentLang, 'en', 'lo'];
    for (const L of order) {
      const v = el.getAttribute('data-' + prefix + L);
      if (v != null) return v;
    }
    return '';
  };
  document.querySelectorAll('[data-en],[data-th],[data-lo],[data-ko]').forEach(el => {
    el.textContent = _pickLangAttr(el, '');
  });
  document.querySelectorAll('[data-ph-en],[data-ph-th],[data-ph-lo],[data-ph-ko]').forEach(el => {
    el.placeholder = _pickLangAttr(el, 'ph-');
  });

  // Update active lang button
  document.querySelectorAll('.lang-btn').forEach(b => {
    b.classList.toggle('active', b.dataset.lang === currentLang);
  });
  // Bento choice tiles are built from <select> option text, which the loops
  // above just rewrote — redraw them so a language switch reaches the tiles.
  if (typeof bcSyncAll === 'function') bcSyncAll();
}

// Helper for JS-generated strings. Pass translations per language; picks the
// current language, falling back to English then Lao. Backward compatible:
// old bi(lo, en) calls still work (th/ko undefined → English fallback).
function bi(lo, en, th, ko) {
  const cur = (typeof currentLang !== 'undefined') ? currentLang : 'en';
  const map = { lo: lo, en: en, th: th, ko: ko };
  if (map[cur] != null) return map[cur];
  return (en != null) ? en : lo;
}
